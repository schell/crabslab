//! CPU-only `SlabItem` impls for fixed-size arrays of primitive types.
//!
//! Each impl is generated for a *concrete* element type with a *literal*
//! length, which is what makes a real fixed-size `type Array` possible: for
//! a generic element type the array length (`T::SLAB_SIZE * N`) is not
//! evaluable on stable Rust (it needs `generic_const_exprs`), so the former
//! const-generic `[T; N]` impl - which fell back to a `Vec<u32>` - was
//! removed in favor of these.
//!
//! Absent values are not slab items; use `Id<T>::NONE` instead of `Option`.
//! Arrays of non-primitive types (structs, tuples) are not slab items
//! either; write the elements individually, or store an `Array<T>` slab
//! pointer.
use crate::SlabItem;

/// Define a `SlabItem` impl for `[$ty; $n]` with a real fixed-size array.
macro_rules! impl_slab_item_for_array {
    ($ty:ty, $n:literal) => {
        impl SlabItem for [$ty; $n] {
            const SLAB_SIZE: usize = { $n * <$ty as SlabItem>::SLAB_SIZE };
            type Array = [u32; $n * <$ty as SlabItem>::SLAB_SIZE];

            fn to_array(data: Self) -> Self::Array {
                let mut dest = Self::array_container();
                for (i, element) in data.iter().enumerate() {
                    let inner = <$ty as SlabItem>::to_array(*element);
                    let offset = i * <$ty as SlabItem>::SLAB_SIZE;
                    dest[offset..offset + <$ty as SlabItem>::SLAB_SIZE].copy_from_slice(AsRef::<
                        [u32],
                    >::as_ref(
                        &inner
                    ));
                }
                dest
            }

            fn from_array(arr: Self::Array) -> Self {
                core::array::from_fn(|i| {
                    let mut inner = <$ty as SlabItem>::array_container();
                    let offset = i * <$ty as SlabItem>::SLAB_SIZE;
                    AsMut::<[u32]>::as_mut(&mut inner).copy_from_slice(
                        &AsRef::<[u32]>::as_ref(&arr)
                            [offset..offset + <$ty as SlabItem>::SLAB_SIZE],
                    );
                    <$ty as SlabItem>::from_array(inner)
                })
            }

            fn array_container() -> Self::Array {
                [0u32; $n * <$ty as SlabItem>::SLAB_SIZE]
            }
        }
    };
}

